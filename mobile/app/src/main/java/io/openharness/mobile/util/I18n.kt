    fun t(lang: Lang, key: String, vars: Map<String, String> = emptyMap()): String {
        var value = when (lang) {
            Lang.FR -> fr[key]
            Lang.EN -> en[key]
        } ?: fr[key] ?: key
        for ((k, v) in vars) value = value.replace("{$k}", v)
        return value
    }

